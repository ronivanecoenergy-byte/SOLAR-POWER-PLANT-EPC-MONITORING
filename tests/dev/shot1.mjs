import { chromium } from '@playwright/test';
import fs from 'node:fs';
const users = JSON.parse(fs.readFileSync('/home/claude/solar-keyplan/data/secrets/demo_users.json','utf8'));
const pw = (e) => users.find(u => u.email === e).password;
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
const p = await ctx.newPage();
const errors = [];
p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
p.on('pageerror', e => errors.push('PAGEERROR ' + e.message));
await p.goto('http://127.0.0.1:5173/');
await p.screenshot({ path: '/tmp/claude-0/shots/01-login.png' });
await p.fill('input[type=email]', 'admin@example.com');
await p.fill('input[type=password]', pw('admin@example.com'));
await p.click('button:has-text("Sign in")');
await p.waitForSelector('h1', { timeout: 30000 });
await p.waitForTimeout(2500);
await p.screenshot({ path: '/tmp/claude-0/shots/02-dashboard.png', fullPage: true });
await p.goto('http://127.0.0.1:5173/#/keyplan');
await p.waitForTimeout(6000);
await p.screenshot({ path: '/tmp/claude-0/shots/03-keyplan.png' });
console.log('errors', errors.slice(0, 10));
await b.close();
